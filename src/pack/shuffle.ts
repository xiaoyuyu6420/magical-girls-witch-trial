/** Stable option order shuffle — position ≠ score, but deterministic per question */

function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** Mulberry32 — deterministic PRNG from seed */
function mulberry32(seed: number): () => number {
  return () => {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Stable shuffle: same questionKey always yields same order.
 * Does not mutate input.
 */
export function shuffleOptionsStable<T>(questionKey: string | number, options: readonly T[]): T[] {
  const arr = options.slice();
  if (arr.length <= 1) return arr;
  const rand = mulberry32(hashString(String(questionKey)));
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}
